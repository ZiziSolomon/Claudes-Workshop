import json, re, sys, collections, math
arts=json.load(open(sys.argv[1]))
N=len(arts)
TOK=re.compile(r"\d[\d   ]*(?:[.,]\d+)?|[\w’'\-]+|[^\w\s]",re.U)
NUM=re.compile(r"^\d")
def base(t): return re.sub(r"\s*\(.*\)$","",t)
def toks(text): return TOK.findall(text)
def norm(tok,name_parts):
    if NUM.match(tok): return '⟨N⟩'
    if tok in name_parts: return '⟨C⟩'
    return tok.lower()
docs={}
for t,txt in arts.items():
    body=txt.split('\n== Notes et références')[0]
    np=set(re.split(r"[\s\-’']",base(t)))-{'','le','la','les','de','du','des','en','sur','sous','et','Saint','Sainte'}
    lines=[]
    for line in body.split('\n'):
        if line.startswith('=='): lines.append(('H',line)); continue
        if not line.strip(): continue
        tk=toks(line)
        lines.append(('P',tk,[norm(x,np) for x in tk]))
    docs[t]=lines
K=4
df=collections.Counter()
for t,lines in docs.items():
    s=set()
    for l in lines:
        if l[0]!='P': continue
        n=l[2]
        for i in range(len(n)-K+1): s.add(tuple(n[i:i+K]))
    df.update(s)
TH=max(10,int(0.03*N))
def classify(n):
    cls=['own']*len(n)
    for i in range(len(n)-K+1):
        if df[tuple(n[i:i+K])]>=TH:
            for j in range(i,i+K): cls[j]='frame'
    for j,x in enumerate(n):
        if x=='⟨N⟩': cls[j]='data'
        elif x=='⟨C⟩' and cls[j]!='frame': cls[j]='name'
    return cls
stats={}
for t,lines in docs.items():
    c=collections.Counter(); empty=0
    for k,l in enumerate(lines):
        if l[0]=='H':
            nxt=lines[k+1] if k+1<len(lines) else None
            if nxt is None or nxt[0]=='H': empty+=1
            continue
        words=[(x,cl) for x,cl in zip(l[1],classify(l[2])) if re.match(r"[\w\d]",x)]
        c.update(cl for _,cl in words)
    tot=sum(c.values()) or 1
    stats[t]=dict(words=tot,own=c['own'],frame=c['frame'],data=c['data'],name=c['name'],own_frac=c['own']/tot,empty_headings=empty)
json.dump(dict(N=N,TH=TH,stats=stats),open('/tmp/work/stats.json','w'),ensure_ascii=False)
# render target
def render(t):
    out=[]
    for l in docs[t]:
        if l[0]=='H':
            lvl=len(l[1])-len(l[1].lstrip('='));out.append(('H',lvl,l[1].strip('= ').strip()));continue
        out.append(('P',list(zip(l[1],classify(l[2])))))
    return out
TGT=sys.argv[2]
# Some boilerplate is generated by templates and absent from raw wikitext; catch it using plain-text extracts of other communes
if len(sys.argv)>4:
    EX=json.load(open(sys.argv[4])); exdf=collections.Counter()
    for t,txt in EX.items():
        if t==TGT or not txt: continue
        npx=set(re.split(r"[\s\-’']",base(t)))-{'','le','la','les','de','du','des','en','sur','sous','et','Saint','Sainte'}
        sset=set()
        for line in txt.split('\n'):
            n=[norm(x,npx) for x in toks(line)]
            for i in range(len(n)-K+1): sset.add(tuple(n[i:i+K]))
        exdf.update(sset)
    for g,c in exdf.items():
        if c>=3: df[g]=max(df[g],TH)
    print('extract-based frame grams',sum(1 for c in exdf.values() if c>=3), 'from',len(EX)-1,'extracts')
ext=json.load(open(sys.argv[3]))['query']['pages'][0]['extract']
docs['__ext__']=[]
np=set(re.split(r"[\s\-’']",base(TGT)))-{'','le','la','les','de','du','des','en','sur','sous','et','Saint','Sainte'}
for line in ext.split('\n== Notes et références')[0].split('\n'):
    if line.startswith('=='): docs['__ext__'].append(('H',line)); continue
    if not line.strip(): continue
    tk=toks(line); docs['__ext__'].append(('P',tk,[norm(x,np) for x in tk]))
json.dump({TGT:render('__ext__')},open('/tmp/work/render.json','w'),ensure_ascii=False)
s=sorted(stats.items(),key=lambda kv:kv[1]['own'])
print('N',N,'TH',TH)
import statistics
print('median own frac',statistics.median(v['own_frac'] for v in stats.values()))
print('median own words',statistics.median(v['own'] for v in stats.values()))
print('least own:',[(k,v['own'],round(v['own_frac'],2)) for k,v in s[:8]])
print('most own:',[(k,v['own'],round(v['own_frac'],2)) for k,v in s[-8:]])
for t in sys.argv[2:3]:
    print(t,stats[t], 'rank by own words', [k for k,_ in s].index(t)+1,'/',N)
